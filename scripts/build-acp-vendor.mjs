#!/usr/bin/env node
/**
 * Vendors the ACP SDK (+ its zod peer dep) into a single committed ESM bundle so
 * the plugin ships with ZERO runtime dependencies — nothing is installed at
 * plugin-install time. The runtime (`lib/acp/client.mjs`) imports the bundle, not
 * the npm package.
 *
 * Output: plugins/multi/scripts/lib/acp/vendor/acp-sdk.bundle.mjs
 *   - format=esm, platform=node, target=node18 (the SDK is ESM-only, Node 18+)
 *   - external: node:* builtins only (everything else, incl. zod, is inlined)
 *   - a banner comment records the exact @agentclientprotocol/sdk version that
 *     built it; a drift-gate unit test asserts this matches package-lock.json.
 *
 * The build is deterministic: a second run produces a byte-identical file (esbuild
 * output is stable for a fixed input + options; the version banner is read from
 * the locked dependency). Run via `npm run build:acp-vendor`.
 */

import { build } from "esbuild";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { mkdirSync, readFileSync, writeFileSync, readFileSync as read } from "node:fs";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");

// The SDK version we bundle — read from the installed package so the banner can
// never drift from what esbuild actually inlined.
const sdkPkgPath = require.resolve("@agentclientprotocol/sdk/package.json");
const sdkVersion = JSON.parse(read(sdkPkgPath, "utf8")).version;

const outDir = join(repoRoot, "plugins", "multi", "scripts", "lib", "acp", "vendor");
const outFile = join(outDir, "acp-sdk.bundle.mjs");

// A tiny entry that re-exports exactly the symbols the runtime needs. Keeping the
// surface explicit (rather than `export *`) makes the bundle smaller and the
// drift-gate test's symbol assertions meaningful.
const entryContents = [
  'export {',
  '  ndJsonStream,',
  '  ClientSideConnection,',
  '  PROTOCOL_VERSION,',
  '} from "@agentclientprotocol/sdk";',
  '',
].join("\n");

const banner =
  `// @generated by scripts/build-acp-vendor.mjs — DO NOT EDIT BY HAND.\n` +
  `// Bundled @agentclientprotocol/sdk version: ${sdkVersion}\n` +
  `// Rebuild with: npm run build:acp-vendor (drift-gate test enforces the version above\n` +
  `// matches the version locked in package-lock.json).`;

async function main() {
  mkdirSync(outDir, { recursive: true });

  const result = await build({
    stdin: {
      contents: entryContents,
      resolveDir: repoRoot,
      sourcefile: "acp-vendor-entry.mjs",
      loader: "js",
    },
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node18",
    // Only Node builtins stay external; zod + the SDK are inlined.
    external: ["node:*"],
    legalComments: "none",
    banner: { js: banner },
    write: false,
  });

  const [output] = result.outputFiles;
  // esbuild emits LF; write verbatim so a second run is byte-identical regardless
  // of the platform's git autocrlf setting.
  writeFileSync(outFile, output.contents);

  const bytes = readFileSync(outFile).length;
  process.stderr.write(
    `[build-acp-vendor] wrote ${outFile} (${bytes} bytes, sdk ${sdkVersion})\n`
  );
}

main().catch((err) => {
  process.stderr.write(`[build-acp-vendor] FAILED: ${err?.stack ?? err}\n`);
  process.exitCode = 1;
});
